def fill_rect(buf, x, y, w, h, rgb):
    if w <= 0 or h <= 0:
        return

    canvas_h = len(buf) // (W * 3)

    x0 = max(0, x)
    y0 = max(0, y)
    x1 = min(W, x + w)
    y1 = min(canvas_h, y + h)

    if x0 >= x1 or y0 >= y1:
        return

    row_width = x1 - x0
    span = row_width * 3
    row = bytes(rgb) * row_width

    for py in range(y0, y1):
        start = (py * W + x0) * 3
        buf[start:start + span] = row


def draw_text(buf, x, y, text, scale, rgb):
    cursor = x

    for ch in text:
        glyph = GLYPHS[ch]

        for row_index, line in enumerate(glyph):
            for col_index, cell in enumerate(line):
                if cell == "#":
                    fill_rect(
                        buf,
                        cursor + col_index * scale,
                        y + row_index * scale,
                        scale,
                        scale,
                        rgb,
                    )

        cursor += 6 * scale


def text_width(text, scale):
    return len(text) * 6 * scale - scale


import zlib
import struct


def write_png(path, w, h, buf):
    def chunk(ctype, data):
        return (
            struct.pack(">I", len(data))
            + ctype
            + data
            + struct.pack(">I", zlib.crc32(ctype + data) & 0xFFFFFFFF)
        )

    signature = b"\x89PNG\r\n\x1a\n"

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)

    raw = bytearray()
    stride = w * 3
    data = bytes(buf)
    for y in range(h):
        start = y * stride
        raw.append(0)
        raw.extend(data[start:start + stride])

    idat = zlib.compress(bytes(raw))

    with open(path, "wb") as f:
        f.write(signature)
        f.write(chunk(b"IHDR", ihdr))
        f.write(chunk(b"IDAT", idat))
        f.write(chunk(b"IEND", b""))


